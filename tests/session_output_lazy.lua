require("vimoi").setup({ diagnostics = { enabled = false }, highlight = { mode = "disabled" } })
local api, util = vim.api, require("vimoi.core.util")
local actions, views, sessions = require("vimoi.api"), require("vimoi.compare"), require("vimoi.render")
local source = api.nvim_create_buf(true, false)
api.nvim_set_current_buf(source)
util.set_buffer_text(source, 'local value = {{ "3" }}\n')
actions.preview()
local preview = assert(views.current())
assert(vim.wait(5000, function()
  return not preview.loading
end, 5))
local state = sessions.get(source)
local output = state.buf
api.nvim_set_current_win(preview.target_win)
vim.cmd("bdelete")
assert(preview.closed and next(state.subscribers) == nil)
assert(not vim.wait(200, function()
  return api.nvim_buf_is_loaded(state.buf)
end, 5))
api.nvim_set_current_win(preview.source_win)
actions.preview()
preview = assert(views.current())
assert(vim.wait(5000, function()
  return not preview.loading and sessions.is_current(source, state.map)
end, 5))
assert(state.buf ~= output and preview.target_buf == state.buf)
assert(util.buffer_text(state.buf) == "local value = 3\n")
output = state.buf
api.nvim_buf_delete(source, { force = true })
assert(not api.nvim_buf_is_valid(output))
