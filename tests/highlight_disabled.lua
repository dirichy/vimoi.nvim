require("vimoi").setup({ diagnostics = { enabled = false }, highlight = { mode = "disabled" } })
local buf = vim.api.nvim_create_buf(false, true)
vim.api.nvim_set_current_buf(buf)
vim.api.nvim_buf_set_lines(buf, 0, -1, false, { "local x = {{ .value }}" })
local highlight = require("vimoi.editor.highlight")
highlight.configure_template_buffer(buf, "lua")
local parser = assert(vim.treesitter.get_parser(buf, "gotmpl"))
parser:parse(true)
assert(not parser:children().lua, "disabled mode enabled host injections")
assert(vim.bo[buf].filetype == "gotmpl" and vim.bo[buf].syntax == "gotmpl")
highlight.configure_template_buffer(buf, "vimoi_missing_parser")
assert(vim.bo[buf].syntax == "gotmpl", "disabled mode enabled a host syntax fallback")
assert(package.loaded["vimoi.editor.host_highlight"] == nil, "disabled mode loaded rendered highlights")
vim.api.nvim_buf_delete(buf, { force = true })
